"""Keep 月建旺相 and 随日辰旺 separate from the seasonal five-state table.

The source calls the next two branches 相 and a general generated by the
day branch 旺. These are distinct predicates, never numerical weights or
replacements for seasonal/internal strength or comprehensive use selection.
"""

from __future__ import annotations

from typing import Any

from fatebridge.core.metaphysics.ren_sources import JINKOU_SOURCE

from ...utils.data import EARTHLY_BRANCHES
from .common import ELEMENT_GENERATES, branch_element_text
from .jinkou_sources import SCAN_SHA256, SCAN_URL


def qi_metadata() -> dict[str, Any]:
    return {
        "ruleset_id": "jinkou_yuejian_richen_excerpt_v1",
        "source_url": JINKOU_SOURCE,
        "source_section": "月建旺相 / 月破休囚",
        "scope": "月建进退、四位相生及日支生将三类证据；日生将原文称随日辰旺，不换算日下五态，不替代季节旺衰或综合取用",
    }


def month_qi_facts(month: str, general: str) -> dict[str, Any]:
    if month not in EARTHLY_BRANCHES or general not in EARTHLY_BRANCHES:
        raise ValueError("月建进退须使用实际月建支和将神本支")
    offset = (EARTHLY_BRANCHES.index(general) - EARTHLY_BRANCHES.index(month)) % 12
    return {
        "month_building_branch": month,
        "jiangshen_branch": general,
        **offset_qi_facts(offset),
    }


def offset_qi_facts(offset: int) -> dict[str, Any]:
    if type(offset) is not int or not 0 <= offset < 12:
        raise ValueError("月建支距须为0至11的整数")
    label = {0: "建旺", 1: "进气相", 2: "进气相", 6: "月破", 11: "退气"}.get(offset)
    return dict(
        month_offset=offset,
        month_qi_label=label,
        month_qi_status="matched_excerpt" if label else "not_classified_by_excerpt",
    )


def day_qi_facts(day: str, general: str) -> dict[str, Any]:
    if day not in EARTHLY_BRANCHES or general not in EARTHLY_BRANCHES:
        raise ValueError("日辰生将须使用实际日支和将神本支")
    day_element, general_element = branch_element_text(day), branch_element_text(
        general
    )
    return dict(
        day_branch=day,
        day_element=day_element,
        jiangshen_element=general_element,
        day_generates_general=ELEMENT_GENERATES[day_element] == general_element,
    )


def qi_basis(month: str, general: str, day: str) -> str:
    monthly, daily = month_qi_facts(month, general), day_qi_facts(day, general)
    return (
        f"月建{month}、将神{general}相距{monthly['month_offset']}支，所选月建条文：{monthly['month_qi_label'] or '未分类'}；"
        f"日支{day}属{daily['day_element']}，{'生' if daily['day_generates_general'] else '未生'}将神{daily['jiangshen_element']}。"
    )


def month_building_metadata() -> dict[str, Any]:
    return {
        "month_building_scan_url": SCAN_URL,
        "month_building_scan_sha256": SCAN_SHA256,
        "month_building_pdf_page": 111,
        "month_building_scope": (
            "京本神将建旺：分别核对贵神固有支、将神本支与月建同支；"
            "不以贵神落地位置或月将本位代替。将神进退另列，贵神进退未据此外推；"
            "不替代四季、日下完整五态及综合取用。"
        ),
    }


def month_building_check(position: str, branch: str, month: str) -> dict[str, Any]:
    if (
        position not in ("贵神", "将神")
        or branch not in EARTHLY_BRANCHES
        or month not in EARTHLY_BRANCHES
    ):
        raise ValueError("神将建旺须使用贵神／将神本支及月建支")
    return dict(
        position=position,
        branch=branch,
        month_building_branch=month,
        matched=branch == month,
    )


def build_jinkou_qi(
    rows: list[dict[str, Any]], *, month_branch: str, day_branch: str
) -> dict[str, Any]:
    general = next(row for row in rows if row["label"] == "将神")
    branch = general["content"]
    monthly = month_qi_facts(month_branch, branch)
    daily = day_qi_facts(day_branch, branch)
    if general["element"] != daily["jiangshen_element"]:
        raise ValueError("日辰生将须使用将神本支的五行")
    building_checks = [
        month_building_check(
            position,
            next(row for row in rows if row["label"] == position)["content"],
            month_branch,
        )
        for position in ("贵神", "将神")
    ]
    building_basis = f"月建{month_branch}；" + "；".join(
        f"{check['position']}本支{check['branch']}{'同' if check['matched'] else '不同'}月建"
        for check in building_checks
    )
    generations = [
        {
            "source_position": left["label"],
            "target_position": right["label"],
            "source_element": left["element"],
            "target_element": right["element"],
            "relation": "生",
        }
        for left in rows
        for right in rows
        if left is not right and ELEMENT_GENERATES[left["element"]] == right["element"]
    ]
    return {
        **qi_metadata(),
        **monthly,
        **daily,
        "month_building_checks": building_checks,
        "month_building_basis": building_basis,
        **month_building_metadata(),
        "interposition_generations": generations,
        "basis": qi_basis(month_branch, branch, day_branch),
    }
