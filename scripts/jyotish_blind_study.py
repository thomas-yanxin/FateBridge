"""Register, seal, and evaluate a Jyotish study using separate input files.

No data are bundled and no forecast probability is generated by this script.
Outputs use exclusive creation; preserve and externally timestamp commitments.
"""

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

from fatebridge.validation.jyotish_study_binding import (
    JyotishProtocol,
    blind_outcome_sheet,
    register,
    reveal_and_evaluate,
    seal_forecasts,
)
from fatebridge.validation.predictions import Forecast, Outcome


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    reg = sub.add_parser("register")
    reg.add_argument("--protocol", required=True)
    reg.add_argument("--model", required=True)
    reg.add_argument(
        "--artifact",
        action="append",
        required=True,
        metavar="NAME=PATH",
        help="Repeat for every protocol artifact; hash actual file bytes before registration",
    )
    seal = sub.add_parser("seal")
    seal.add_argument("--registration", required=True)
    seal.add_argument("--forecasts", required=True)
    seal.add_argument("--evidence", action="append", required=True, metavar="CASE=PATH")
    sheet = sub.add_parser("blind-sheet")
    sheet.add_argument("--registration", required=True)
    score = sub.add_parser("evaluate")
    score.add_argument("--registration", required=True)
    score.add_argument("--sealed", required=True)
    score.add_argument("--outcomes", required=True)
    score.add_argument(
        "--outcome-source", action="append", default=[], metavar="CASE=PATH"
    )
    for command in (reg, seal, sheet, score):
        command.add_argument("--output", required=True)
    args = parser.parse_args()
    now = datetime.now(timezone.utc)

    def files(items):
        bindings = {}
        for item in items:
            if "=" not in item:
                parser.error("file bindings must use NAME=PATH")
            name, path = item.split("=", 1)
            if not name or name in bindings:
                parser.error("empty or duplicate file binding")
            bindings[name] = Path(path).read_bytes()
        return bindings

    if args.action == "register":
        result = register(
            JyotishProtocol.model_validate(read(args.protocol)),
            Path(args.model).read_bytes(),
            at=now,
            artifacts=files(args.artifact),
        )
    elif args.action == "seal":
        result = seal_forecasts(
            read(args.registration),
            [Forecast.model_validate(f) for f in read(args.forecasts)],
            at=now,
            evidence=files(args.evidence),
        )
    elif args.action == "blind-sheet":
        result = blind_outcome_sheet(read(args.registration))
    else:
        result = reveal_and_evaluate(
            read(args.registration),
            read(args.sealed),
            [Outcome.model_validate(o) for o in read(args.outcomes)],
            at=now,
            outcome_sources=files(args.outcome_source),
        )
    # Never silently overwrite an earlier commitment or study result.
    with Path(args.output).open("x", encoding="utf-8") as output:
        output.write(
            json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
        )
    print(
        json.dumps(
            {
                "action": args.action,
                "output": args.output,
                "authority_certified": False,
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
