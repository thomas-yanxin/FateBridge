"""Isolate surviving-root qualification changes from numeric energy changes.

This is an exposed engineering regression, not an independent classical oracle.
The archived v3 kernel runs with explicitly fingerprinted current shared data.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.machinery
import importlib.util
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

from fatebridge.core import strength
from fatebridge.core.calendar import BaZiCalendar
from fatebridge.core.elements import ElementAnalysis

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = ROOT / "docs/validation/bazi-root-qualification-strength-baseline-v3.py.txt"
ARCHIVE_SHA256 = "997566b844957eb49c374b734886222b4664632f61abffd9ebac462f6f36854f"
V4_ARCHIVE = ROOT / "docs/validation/bazi-complete-bureau-strength-baseline-v4.py.txt"
V4_SHA256 = "606d8255222f1f3af4a9926737eb4a3fd20e508b135fdc7c1fa420bc2a63714e"
ORDER = ("year", "month", "day", "hour")
NUMERIC_FIELDS = (
    "support_strength",
    "weaken_strength",
    "support_share",
    "effective_elements",
    "branch_budgets",
    "relations",
    "roots",
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_archive(path: Path, expected: str, version: str) -> Any:
    if sha256(path) != expected:
        raise ValueError(f"Archived {version} kernel changed")
    name = f"fatebridge.core._root_qualification_baseline_{version}"
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    spec = importlib.util.spec_from_loader(name, loader)
    assert spec is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    loader.exec_module(module)
    return module


def load_v3() -> Any:
    return _load_archive(ARCHIVE, ARCHIVE_SHA256, "v3")


def audit(*, historical_v4_replay: bool = False) -> dict[str, Any]:
    baseline = load_v3()
    compared = (
        _load_archive(V4_ARCHIVE, V4_SHA256, "v4") if historical_v4_replay else strength
    )
    examples = [
        ("published_pair_first_person", "庚午 辛巳 庚辰 辛巳"),
        ("single_yang_growth_root_source_case", "壬寅 壬寅 庚辰 辛巳"),
        ("damaged_yang_growth_source_case", "壬寅 戊申 壬辰 壬寅"),
        ("body_light_seal_heavy_source_case", "己巳 癸酉 癸未 庚申"),
        ("synthetic_double_growth_case", "乙亥 壬午 甲辰 乙亥"),
    ]
    probes = [
        (
            label,
            dict(zip(ORDER, [(p[0], p[1]) for p in text.split()], strict=True)),
        )
        for label, text in examples
    ]
    # These charts are generated by current calendar code for causal regression;
    # they are not expected calendar answers or independent source labels.
    zone = ZoneInfo("Asia/Shanghai")
    for year in range(2000, 2010):
        for month in range(1, 13):
            for hour in (0, 6, 12, 18):
                instant = datetime(year, month, 15, hour, tzinfo=zone)
                chart = BaZiCalendar.get_four_pillars(
                    instant, timezone_name="Asia/Shanghai", civil_datetime=instant
                )
                probes.append((instant.isoformat(), chart))
    numeric_differences = []
    changed = []
    focus = []
    for index, (label, chart) in enumerate(probes):
        phases = ElementAnalysis.seasonal_phases(chart["month"][1])
        before = baseline._evaluate(chart, phases, baseline.DEFAULT_POLICY)
        after = compared._evaluate(chart, phases, compared.DEFAULT_POLICY)
        differences = [f for f in NUMERIC_FIELDS if before[f] != after[f]]
        if differences:
            numeric_differences.append({"case_id": label, "fields": differences})
        observation = {
            "case_id": label,
            "pillars": ["".join(chart[p]) for p in ORDER],
            "v3_strength": before["strength_level"],
            "v4_strength": after["strength_level"],
            "v3_rule": before["structural_decision"]["rule"],
            "v4_rule": after["structural_decision"]["rule"],
            "support_share_before": before["support_share"],
            "support_share_after": after["support_share"],
            "v3_vigorous_roots": before["structural_decision"]["vigorous_roots"],
            "v4_vigorous_roots": after["structural_decision"]["vigorous_roots"],
        }
        if before["strength_level"] != after["strength_level"]:
            changed.append(observation)
        if index < len(examples):
            focus.append(
                {**observation, "root_qualifications": after["root_qualifications"]}
            )
    paths = [
        "src/fatebridge/core/strength.py",
        "src/fatebridge/core/storage_movement.py",
        "src/fatebridge/core/classical_roots.py",
        "src/fatebridge/utils/data.py",
        "src/fatebridge/core/calendar.py",
        "uv.lock",
    ]
    return {
        "report_id": "root_qualification_numeric_isolation_v1",
        "classification": "exposed_engineering_causal_regression_not_independent_accuracy_oracle",
        "baseline_kernel_sha256": ARCHIVE_SHA256,
        "baseline_runtime_scope": "exact archived v3 kernel with fingerprinted current shared dependencies, not a fully archived historical environment",
        "compared_method_id": compared.STRENGTH_METHOD_ID,
        "actual_production_method_id": strength.STRENGTH_METHOD_ID,
        "comparison_mode": (
            "historical_v3_to_v4" if historical_v4_replay else "v3_to_current"
        ),
        "historical_v4_sha256": V4_SHA256 if historical_v4_replay else None,
        "current_dependencies": {p: sha256(ROOT / p) for p in paths},
        "numeric_fields_compared": list(NUMERIC_FIELDS),
        "probe_count": len(probes),
        "civil_input_probe_count": len(probes) - len(examples),
        "all_numeric_components_unchanged": not numeric_differences,
        "numeric_differences": numeric_differences,
        "strength_label_changes": changed,
        "focus_cases": focus,
        "complete_classical_acceptance": False,
        "real_world_efficacy": "not_tested",
        "authority_certified": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument(
        "--historical-v4-replay",
        action="store_true",
        help="Replay the archived v4 root-qualification change, not later production changes",
    )
    args = parser.parse_args()
    if args.output and args.output.exists():
        raise FileExistsError("Audit outputs are immutable; choose a new output path")
    result = audit(historical_v4_replay=args.historical_v4_replay)
    if args.output:
        target = args.output.resolve()
        if target in {ARCHIVE.resolve(), V4_ARCHIVE.resolve()}:
            raise ValueError("Cannot overwrite the archived baseline")
        target.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(
        json.dumps(
            {
                "probe_count": result["probe_count"],
                "all_numeric_components_unchanged": result[
                    "all_numeric_components_unchanged"
                ],
                "strength_label_change_count": len(result["strength_label_changes"]),
                "complete_classical_acceptance": False,
            },
            ensure_ascii=False,
        )
    )
    return 0 if result["all_numeric_components_unchanged"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
