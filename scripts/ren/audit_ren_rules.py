"""Audit all 720 subtype names, added Jin Kou qi rules and HKO boundaries.

No expected label is generated by the calculator. Raw transcription and
separately collated labels both remain in the report. Literal mismatches do
not become passes merely because a broader source name is compatible.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "tests/fixtures/ren_rule_depth_v3"
BRANCHES = "子丑寅卯辰巳午未申酉戌亥"
HOUSES = dict(zip("甲乙丙丁戊己庚辛壬癸", "寅辰巳未巳未申戌亥丑"))
MAJORS = dict(
    zip(
        "大寒 雨水 春分 谷雨 小满 夏至 大暑 处暑 秋分 霜降 小雪 冬至".split(),
        "子亥戌酉申未午巳辰卯寅丑",
    )
)
TERM_NAMES = "小寒 大寒 立春 雨水 惊蛰 春分 清明 谷雨 立夏 小满 芒种 夏至 小暑 大暑 立秋 处暑 白露 秋分 寒露 霜降 立冬 小雪 大雪 冬至".split()


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_reference(corpus: Path = CORPUS) -> dict[str, Any]:
    frozen = json.loads((corpus / "freeze.json").read_text())
    expected = {"naming.json", "qi.json", "calendar-sources.json", "source-pages.pdf"}
    if set(frozen["files"]) != expected or {
        p.name for p in corpus.iterdir() if p.is_file()
    } != expected | {"freeze.json"}:
        raise ValueError("Reference file set changed")
    for name, checksum in frozen["files"].items():
        if sha(corpus / name) != checksum:
            raise ValueError(f"Reference changed after freeze: {name}")
    data = {
        Path(n).stem: json.loads((corpus / n).read_text())
        for n in expected
        if n.endswith(".json")
    }
    # Capture paths remain in the frozen source record; current readers use
    # the maintained data location with the same independently pinned bytes.
    data["calendar-sources"]["files"] = {
        name.replace(
            "tests/fixtures/fengshui_calendar_v1/", "tests/data/fengshui_calendar_v1/"
        ): checksum
        for name, checksum in data["calendar-sources"]["files"].items()
    }
    for name, checksum in data["calendar-sources"]["files"].items():
        if sha(ROOT / name) != checksum:
            raise ValueError(f"Reference calendar source changed: {name}")
    return data


def audit() -> dict[str, Any]:
    ref = load_reference()
    from scripts.ren import audit_ren_classical as v1
    from scripts.ren import audit_ren_depth as v2

    old = v2.load_reference()
    scan = v2.load_scan_reference()
    # Only after all source inventories have been verified, load production.
    from fatebridge.core.almanac import get_solar_terms_for_year
    from fatebridge.core.metaphysics.liureng import build_liureng_board
    from fatebridge.services.metaphysics import _build_analysis_seed

    def normal(text):
        return (
            text.removeprefix("改正")
            .replace("嚆矢", "蒿矢")
            .replace("知ㄧ", "知一")
            .split("、")
        )

    table = {(c["day"], c["gan_upper"]): c for c in old["tanyuan-table"]["cases"]}
    for row in scan["missing_table_rows"]:
        key = row["day"], row["gan_upper"]
        assert key not in table
        labels = next(
            c["labels"]
            for c in ref["naming"]["supplement_labels"]
            if (c["day"], c["gan_upper"]) == key
        )
        table[key] = {**row, "style": "、".join(labels)}
    assert len(table) == 720
    corrections = {
        (c["day"], c["gan_upper"]): c
        for c in ref["naming"]["transcription_corrections"]
    }
    comparisons, raw_failures, collated_failures, branch_failures = [], [], [], []
    for key, case in table.items():
        offset = (
            BRANCHES.index(case["gan_upper"]) - BRANCHES.index(HOUSES[case["day"][0]])
        ) % 12
        board = build_liureng_board(
            v1.make_seed({"day": case["day"], "hour": "子"}),
            month_general_override=BRANCHES[offset],
        )
        actual = board["classification"]["labels"]
        raw = normal(case["style"])
        correction = corrections.get(key)
        expected = correction["scan_labels"] if correction else raw
        if correction and raw != correction["transcribed_labels"]:
            raise ValueError(
                "Reference transcription correction no longer matches retained source"
            )
        row = {
            "day": key[0],
            "gan_upper": key[1],
            "actual": actual,
            "transcribed": raw,
            "selected_collation": expected,
            "source_page": (
                correction["original_pdf_page"]
                if correction
                else case.get("original_pdf_page")
            ),
            "raw_matched": actual == raw,
            "collated_matched": actual == expected,
        }
        if actual != expected:
            row["relationship"] = (
                "calculated_subtype_of_broad_source_name"
                if (expected == ["涉害"] and actual[0] in ("见机", "察微", "缀瑕"))
                or (expected == ["重审"] and actual == ["始入"])
                else "literal_disagreement"
            )
            row["calculation_basis"] = board["classification"]["basis"]
        comparisons.append(row)
        if not row["raw_matched"]:
            raw_failures.append(row)
        if not row["collated_matched"]:
            collated_failures.append(row)
        sequence = [
            board["three_transmissions"][k]["branch"]
            for k in ("initial", "middle", "final")
        ]
        if sequence != case["transmissions"]:
            branch_failures.append(
                {
                    "day": key[0],
                    "gan_upper": key[1],
                    "actual": sequence,
                    "expected": case["transmissions"],
                }
            )

    qi_checks = []

    def qi_case(month, general, day="甲子"):
        return v1.observe_jinkou(
            dict(month=month, general=general, day=day, hour="子", ground="子")
        )["qi_evidence"]

    def check(key, actual, expected):
        qi_checks.append(
            dict(id=key, actual=actual, expected=expected, matched=actual == expected)
        )

    for row in ref["qi"]["month_examples"]:
        check(
            f"month.{row['month']}.{row['general']}",
            qi_case(row["month"], row["general"])["month_qi_label"],
            row["label"],
        )
    for branch in ref["qi"]["month_building"]:
        check(f"building.{branch}", qi_case(branch, branch)["month_qi_label"], "建旺")
    for row in ref["qi"]["month_breaks"]:
        check(
            f"break.{row['month']}",
            qi_case(row["month"], row["general"])["month_qi_label"],
            "月破",
        )
    for row in ref["qi"]["day_generation_examples"]:
        day = ("甲" if row["day_branch"] in "子寅辰午申戌" else "乙") + row[
            "day_branch"
        ]
        check(
            f"day_growth.{day}.{row['general']}",
            qi_case("寅", row["general"], day)["day_generates_general"],
            row["generated"],
        )

    calendar, boundary_probes = [], []
    for name in ref["calendar-sources"]["files"]:
        if not name.endswith(".xml"):
            continue
        xml = ET.fromstring((ROOT / name).read_bytes())
        year = int(xml.tag.removeprefix("SolarTerms_"))
        terms = {t.name: t for t in get_solar_terms_for_year(year, "Asia/Hong_Kong")}
        published_rows = xml.findall("Data")
        if len(published_rows) != 24:
            raise ValueError("Reference solar-term inventory changed")
        for term, published in zip(TERM_NAMES, published_rows):
            at = datetime.fromisoformat(
                f"{year}-{published.findtext('M')}-{published.findtext('D')}T{published.findtext('hm')}:00+08:00"
            )
            error = abs((terms[term].moment - at).total_seconds())
            calendar.append(
                dict(
                    year=year,
                    term=term,
                    difference_from_published_minute_seconds=round(error, 3),
                    matched=error <= 60,
                )
            )
            if term not in MAJORS:
                continue
            for zone in ("Asia/Shanghai", "UTC", "America/New_York"):
                actual = []
                for minutes in (-2, 2):
                    local = (at + timedelta(minutes=minutes)).astimezone(ZoneInfo(zone))
                    seed = _build_analysis_seed(
                        analysis_year=local.year,
                        analysis_month=local.month,
                        analysis_day=local.day,
                        analysis_hour=local.hour,
                        analysis_minute=local.minute,
                        analysis_second=local.second,
                        analysis_timezone=zone,
                        analysis_longitude=135,
                        use_true_solar_time=True,
                    )
                    actual.append(build_liureng_board(seed)["month_general"]["branch"])
                expected = [
                    BRANCHES[(BRANCHES.index(MAJORS[term]) + 1) % 12],
                    MAJORS[term],
                ]
                boundary_probes.append(
                    dict(
                        year=year,
                        term=term,
                        zone=zone,
                        actual=actual,
                        expected=expected,
                        matched=actual == expected,
                    )
                )

    engineering = not branch_failures and all(
        c["matched"] for c in qi_checks + calendar + boundary_probes
    )
    requirements = [
        {
            "id": "calendar.selected_official_instants_and_boundaries",
            "status": (
                "verified"
                if all(c["matched"] for c in calendar + boundary_probes)
                else "contradicted"
            ),
            "evidence": "hko_calendar and month_general_boundary_probes",
        },
        {
            "id": "calendar.full_supported_domain",
            "status": "unverified",
            "evidence": "Current independent coverage is only 2024,2026,2027,2028; other years, historical clock conventions and all date boundaries are not certified.",
        },
        {
            "id": "classical.complete_720_transmission_sequences",
            "status": (
                "verified"
                if len(table) == 720 and not branch_failures
                else "contradicted"
            ),
            "evidence": "branch_sequences; mixed transcription and selected scan collation",
        },
        {
            "id": "classical.literal_720_subtype_names",
            "status": "verified" if not collated_failures else "contradicted",
            "evidence": "names.remaining_literal_mismatches; broader names are not counted as literal matches",
        },
        {
            "id": "classical.complete_selected_original_rules",
            "status": "incomplete",
            "evidence": "Full internal/day strength, composite use selection, classical patterns and unresolved textual contradictions are not completely adjudicated.",
        },
        {
            "id": "interpretation.engine_and_transport_fact_fidelity",
            "status": "unverified_by_this_script",
            "evidence": "Separate native REST/MCP/CLI, snapshot and same-run claim tests are required; this script does not execute them.",
        },
        {
            "id": "interpretation.real_model_free_text_fidelity",
            "status": "unverified",
            "evidence": "No independent real-model behavior evaluation is supplied by this audit.",
        },
    ]
    complete = all(r["status"] == "verified" for r in requirements)
    return {
        "implemented_rule_checks_passed": engineering,
        "names": {
            "case_count": len(comparisons),
            "raw_exact_matches": len(comparisons) - len(raw_failures),
            "after_selected_scan_collation_exact_matches": len(comparisons)
            - len(collated_failures),
            "raw_mismatches": raw_failures,
            "remaining_literal_mismatches": collated_failures,
            "scan_corrections": ref["naming"]["transcription_corrections"],
            "literal_name_conformance_passed": not collated_failures,
            "normalization_scope": "嚆矢/蒿矢, 知ㄧ/知一, editorial 改正 prefix only; no subtype or contradictory-label erasure",
        },
        "branch_sequences": {"case_count": len(table), "failures": branch_failures},
        "qi_checks": qi_checks,
        "hko_calendar": calendar,
        "month_general_boundary_probes": boundary_probes,
        "calendar_scope": "96 published minutes in 2024,2026,2027,2028; 48 zhongqi boundaries across 3 zones, before/after. Not all supported years or second-level astronomical accuracy.",
        "three_axes": {
            "calendar": "selected_published_instants_and_boundary_probes",
            "classical": "incomplete; literal names and broader source contradictions remain",
            "interpretation": "deterministic explanations tied to calculation facts; unrestricted model prose not validated",
        },
        "requirement_inventory": requirements,
        "classical_acceptance_passed": all(
            r["status"] == "verified"
            for r in requirements
            if r["id"].startswith("classical.")
        ),
        "goal_complete": complete,
        "provenance": {
            "reference_freeze_sha256": sha(CORPUS / "freeze.json"),
            "prior_v2_freeze_sha256": sha(v2.CORPUS / "freeze.json"),
            "prior_scan_freeze_sha256": sha(v2.SCAN_CORPUS / "freeze.json"),
            "implementation_files": {
                name: sha(ROOT / name)
                for name in (
                    "src/fatebridge/core/metaphysics/liureng.py",
                    "src/fatebridge/core/metaphysics/liureng_patterns.py",
                    "src/fatebridge/core/metaphysics/jinkou.py",
                    "src/fatebridge/core/metaphysics/jinkou_qi.py",
                    "src/fatebridge/core/metaphysics/ren_evidence.py",
                    "src/fatebridge/core/requests/metaphysics.py",
                    "src/fatebridge/core/output_chinese.py",
                    "src/fatebridge/services/metaphysics.py",
                    "src/fatebridge/core/almanac.py",
                    "src/fatebridge/core/calendar.py",
                )
            },
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--require-three-axis-completion", action="store_true")
    args = parser.parse_args()
    report = audit()
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(
            json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
            encoding="utf-8",
        )
    print(
        json.dumps(
            dict(
                implemented_rule_checks_passed=report["implemented_rule_checks_passed"],
                names_raw_exact=report["names"]["raw_exact_matches"],
                names_after_selected_collation_exact=report["names"][
                    "after_selected_scan_collation_exact_matches"
                ],
                names_total=report["names"]["case_count"],
                literal_name_conformance_passed=report["names"][
                    "literal_name_conformance_passed"
                ],
                qi_checks=len(report["qi_checks"]),
                official_instants=len(report["hko_calendar"]),
                boundary_pairs=len(report["month_general_boundary_probes"]),
                goal_complete=report["goal_complete"],
            ),
            ensure_ascii=False,
        )
    )
    return (
        0
        if report["implemented_rule_checks_passed"]
        and (not args.require_three_axis_completion or report["goal_complete"])
        else 1
    )


if __name__ == "__main__":
    raise SystemExit(main())
