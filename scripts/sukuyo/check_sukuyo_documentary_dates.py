"""Check literal printed chronicle date/ganzhi facts against the named reference.

Expected lunar dates and day labels are transcribed from the printed pages,
never generated by the calendar under test. These are four correlated facts
from one month, not four independent historical calendars or outcome samples.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import date
from pathlib import Path

from fatebridge.core.sukuyo import calendar_mansion
from fatebridge.core.sukuyo_historical_calendar import SOURCE
from fatebridge.core.sukuyo_sources import load_source

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/data/sukuyo-documentary-dates.json"


def verify_documentary_controls(*, capture_dir: Path | None = None) -> dict:
    raw = FIXTURE.read_bytes()
    fixture = json.loads(raw)
    capture_checks = []
    if capture_dir is not None:
        for record in fixture["captured_source_files"]:
            path = capture_dir / record["file"]
            actual_hash = hashlib.sha256(path.read_bytes()).hexdigest()
            if actual_hash != record["sha256"]:
                raise ValueError(
                    "Documentary source capture fingerprint changed: " + record["file"]
                )
            capture_checks.append(record["file"])
    bundle = load_source(SOURCE)
    rows, mismatches = [], []
    for control in fixture["controls"]:
        expected = control["lunar_fields"]
        months = [
            month
            for month in bundle.data["months"]
            if [month[1], month[2], month[3]] == [expected[0], expected[1], expected[3]]
        ]
        if len(months) != 1 or not 1 <= expected[2] <= months[0][4]:
            raise ValueError(
                "Printed documentary date cannot map to one admitted reference month"
            )
        civil = date.fromordinal(months[0][0] + expected[2] - 1)
        actual = calendar_mansion(
            civil.isoformat(),
            time_text="12:00:00",
            zone="+09:00",
            calendar_basis="japanese_naoj_historical_utc09",
        )
        actual_fields = [
            actual[k]
            for k in ("lunar_year", "lunar_month", "lunar_day", "is_leap_month")
        ]
        label = actual["calendar_reference"]["day_ganzhi_reference"]["name"]
        row = {
            **control,
            "reference_civil_date": civil.isoformat(),
            "calculated_lunar_fields": actual_fields,
            "calculated_day_ganzhi": label,
            "matches_printed_control": actual_fields == expected
            and label == control["day_ganzhi"],
        }
        rows.append(row)
        if not row["matches_printed_control"]:
            mismatches.append(row)
    conflicts = []
    for conflict in fixture["secondary_paper_conflicts"]:
        control = next(
            row for row in rows if row["id"] == conflict["documentary_control_id"]
        )
        conflicts.append(
            {
                **conflict,
                "calculated_day_ganzhi": control["calculated_day_ganzhi"],
                "paper_and_printed_chronicle_disagree": conflict["paper_day_ganzhi"]
                != control["day_ganzhi"],
                "engine_day_shift_applied": False,
                "author_correction_or_autograph_diary_verified": False,
            }
        )
    return {
        "format": "sukuyo_documentary_date_check_v1",
        "fixture_sha256": hashlib.sha256(raw).hexdigest(),
        "runtime_source_sha256": bundle.sha256,
        "bounded_month_count": 1,
        "printed_controls_checked": len(rows),
        "controls": rows,
        "mismatches": mismatches,
        "retained_secondary_paper_conflicts": conflicts,
        "source_capture_files_hash_checked": capture_checks,
        "independent_original_manuscript_collation": False,
        "whole_historical_calendar_accepted": False,
        "scope": fixture["scope"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture-dir", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    result = verify_documentary_controls(capture_dir=args.capture_dir)
    text = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.write_text(text)
    else:
        print(text, end="")
    return bool(result["mismatches"])


if __name__ == "__main__":
    raise SystemExit(main())
