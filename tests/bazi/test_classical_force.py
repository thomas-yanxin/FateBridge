def chart(text):
    return dict(zip(("year", "month", "day", "hour"), map(tuple, text.split())))


def test_primary_reference_retains_unknown_labels_and_transcription_variants() -> None:
    path = FIXTURE / "reference.json"
    assert (
        hashlib.sha256(path.read_bytes()).hexdigest()
        == path.with_suffix(".sha256").read_text().strip()
    )
    ref = json.loads((FIXTURE / "reference.json").read_text())
    assert len(ref["cases"]) == 34
    assert sum(c["expected_strength"] is None for c in ref["cases"]) == 27
    assert {c["label_kind"] for c in ref["cases"]} == {
        "unknown",
        "explicit_body_strength",
        "explicit_body_heavy_light",
    }
    li = next(c for c in ref["cases"] if c["name"] == "李状元")
    assert li["pillars"][-1] == "乙亥"
    assert li["transcription_variants"][0]["pillars"][-1] == "己亥"
    assert li["transcription_variants"][0]["status"] == "inferred_not_primary_reading"


def test_body_and_seal_roots_are_distinct_in_the_explicit_source_counterexample() -> (
    None
):
    # Source PDF73: 身轻印重. No expected label is generated by this model.
    pillars = chart("己巳 癸酉 癸未 庚申")
    model = ElementAnalysis.analyze_day_master_strength(pillars)
    evidence = build_natal_evidence(pillars, model)
    profile = evidence["force_components"]
    components = profile["components"]
    assert components["body"]["element"] == "水"
    assert components["seal"]["element"] == "金"
    assert [
        (r["pillar"], r["stem"]) for r in components["body"]["physical_hidden_roots"]
    ] == [("hour", "壬")]
    assert [
        (r["pillar"], r["stem"]) for r in components["seal"]["physical_hidden_roots"]
    ] == [("year", "庚"), ("month", "辛"), ("hour", "庚")]
    assert components["body"]["revealed_positions"] == ["month"]
    assert components["seal"]["revealed_positions"] == ["hour"]
    assert profile["engineering_composition"]["strength_level"] == "强"
    assert (
        profile["engineering_composition"]["body_seal_energy_relation"]
        == "seal_greater"
    )
    adjudication = profile["classical_adjudication"]
    assert adjudication["status"] == "not_adjudicated"
    assert adjudication["body_strength"] is None
    assert adjudication["seal_weight"] is None
    assert adjudication["body_seal_relation"] is None
    assert adjudication["ordinary_fuyi_applicable"] is None
    assert adjudication["observed_body_root_positions"] == ["hour"]
    assert adjudication["observed_seal_root_positions"] == ["year", "month", "hour"]
    assert adjudication == model["classical_adjudication"]
    # Every quantity reuses the same calculation; no second evaluation or score.
    energies = model["assessment"]["effective_elements"]
    assert {
        v["element"]: v["engineering_energy"] for v in components.values()
    } == energies
    ids = {
        s["evidence_id"] for entries in evidence["ten_gods"].values() for s in entries
    }
    assert all(set(c["source_star_refs"]) <= ids for c in components.values())


def test_missing_assessment_is_unknown_and_never_recomputed(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    def forbidden(*args, **kwargs):
        raise AssertionError("Missing evidence must not trigger another calculation")

    monkeypatch.setattr(ElementAnalysis, "analyze_day_master_strength", forbidden)
    profile = build_natal_evidence(chart("己巳 癸酉 癸未 庚申"))["force_components"]
    assert profile["engineering_composition"]["status"] == "not_supplied"
    assert profile["engineering_composition"]["body_within_support_share"] is None
    assert all(c["engineering_energy"] is None for c in profile["components"].values())
    assert profile["components"]["seal"]["physical_hidden_roots"]


def test_engineering_policy_changes_do_not_adjudicate_source_force(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    from dataclasses import replace

    from fatebridge.core import source_annotations, strength

    def forbidden():
        raise AssertionError("A source grade must not be looked up as a calculation")

    monkeypatch.setattr(source_annotations, "_index", forbidden)
    pillars = chart("己巳 癸酉 癸未 庚申")
    original = ElementAnalysis.comprehensive_analysis(pillars)
    assert original["day_master"]["engineering_index"]["strength_level"] == "强"
    assert original["engineering_favorable_elements"] == ["木", "土", "火"]
    monkeypatch.setattr(
        strength,
        "DEFAULT_POLICY",
        replace(strength.DEFAULT_POLICY, weak_share=0.98, strong_share=0.99),
    )
    alternative = ElementAnalysis.comprehensive_analysis(pillars)
    assert alternative["day_master"]["engineering_index"]["strength_level"] == "弱"
    assert alternative["engineering_favorable_elements"] == ["水", "金"]
    assert (
        original["day_master"]["classical_adjudication"]
        == alternative["day_master"]["classical_adjudication"]
    )
    for result in (original, alternative):
        assert result["favorable_elements"] == []
        assert result["favorable_elements_status"] == "not_adjudicated"


def test_source_body_grade_alone_does_not_establish_the_fuyi_route() -> None:
    result = ElementAnalysis.analyze_day_master_strength(chart("己巳 癸酉 癸未 庚申"))
    result["classical_adjudication"].update(status="adjudicated", body_strength="强")
    assert ElementAnalysis.get_favorable_elements(result) == []
    result["classical_adjudication"]["ordinary_fuyi_applicable"] = True
    assert [e.value for e in ElementAnalysis.get_favorable_elements(result)] == [
        "木",
        "土",
        "火",
    ]


@pytest.mark.parametrize(
    "key",
    [
        "bazi_birth",
        "bazi_career",
        "bazi_wealth",
        "bazi_health",
        "bazi_children",
        "bazi_education",
        "bazi_personality",
        "bazi_relatives",
        "bazi_marriage",
        "bazi_romance",
    ],
)
def test_projected_force_components_match_rest_native_mcp_and_cli(
    key: str, rest, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    spec = SPECS[key]
    args = {
        "birth_year": 1990,
        "birth_month": 5,
        "birth_day": 15,
        "birth_hour": 10,
        "birth_timezone": "Asia/Shanghai",
        "gender": "男",
        "analysis_year": 2026,
        "analysis_month": 10,
        "analysis_day": 12,
    }
    fields = suggested_fields(spec, view="force_components")
    response = rest.post(
        spec.rest_path,
        json=args,
        params={
            "fields": fields,
            "strict_fields": True,
            "include_snapshot_text": False,
        },
    )
    projected = {
        **args,
        "fields": fields,
        "strict_fields": True,
        "include_snapshot_text": False,
    }
    protocol = asyncio.run(native(spec, projected))
    code, local = call_cli(
        spec,
        args,
        tmp_path,
        capsys,
        flags=["--response-char-limit", "0", "--strict-fields", "--fields", *fields],
    )
    assert response.status_code == 200 and code == 0 and not protocol.is_error
    outputs = [response.json(), local, protocol.structured_content]
    assert business(outputs[0]) == business(outputs[1]) == business(outputs[2])
    for result in outputs:
        Draft202012Validator(spec.output_model.model_json_schema()).validate(result)
        evidence = (
            result["bazi_birth"]["structure_profile"]["evidence_chain"]
            if key == "bazi_birth"
            else result[key.removeprefix("bazi_") + "_analysis"]["evidence_chain"]
        )
        assert (
            evidence["force_components"]["engineering_composition"]["status"]
            == "supplied_calculation"
        )


@pytest.mark.parametrize(
    "topic",
    [
        "birth",
        "career",
        "wealth",
        "health",
        "children",
        "education",
        "personality",
        "relatives",
        "marriage",
        "romance",
    ],
)
def test_all_ten_published_force_views_preserve_references(topic: str, rest) -> None:
    spec = SPECS["bazi_" + topic]
    fields = suggested_fields(spec, view="force_components")
    response = rest.post(
        spec.rest_path,
        json={
            "birth_year": 1990,
            "birth_month": 5,
            "birth_day": 15,
            "birth_hour": 10,
            "gender": "男",
            "analysis_year": 2026,
            "analysis_month": 10,
            "analysis_day": 12,
        },
        params={
            "fields": fields,
            "strict_fields": True,
            "include_snapshot_text": False,
        },
    )
    assert response.status_code == 200, response.text
    result = response.json()
    evidence = (
        result["bazi_birth"]["structure_profile"]["evidence_chain"]
        if topic == "birth"
        else result[topic + "_analysis"]["evidence_chain"]
    )
    profile = evidence["force_components"]
    ids = {
        s["evidence_id"] for entries in evidence["ten_gods"].values() for s in entries
    }
    assert len(profile["components"]) == 5
    assert all(
        set(c["source_star_refs"]) <= ids for c in profile["components"].values()
    )
