@pytest.mark.parametrize("month", ["子", "午"])
def test_boundary_months_are_unknown_until_explicitly_resolved(month):
    assert resolve_half_year(month, None) == (None, "boundary_month_unresolved")
    for flag in (False, True):
        assert resolve_half_year(month, flag) == (flag, "explicit_half_year")


def test_mixed_hexagrams_do_not_depend_on_gender_or_solstice_half():
    # Metamorphic coverage over all 62 mixed bit patterns, not birth cases.
    for bits in product((0, 1), repeat=6):
        if len(set(bits)) == 1:
            continue
        for h in "子丑寅卯辰巳午未申酉戌亥":
            first = placement(list(bits), h, True, None)
            for male, half in product((False, True), (False, True)):
                assert placement(list(bits), h, male, half) == first


@pytest.mark.parametrize("bad", ["false", "true", 0, 1, [], {}])
def test_placement_cannot_coerce_half_or_gender(bad):
    with pytest.raises(ValueError):
        placement([1] * 6, "巳", False, bad)
    with pytest.raises(ValueError):
        placement([1] * 6, "巳", bad, False)
    with pytest.raises(ValueError):
        resolve_half_year("午", bad)


@pytest.mark.parametrize("case", SOURCE["modern_selection_probes"])
def test_public_clock_resolves_half_and_copies_the_actual_same_run_trace(case):
    r = build_heluo_result(
        date=case["date"],
        time=case["time"],
        gender=case["gender"],
        use_true_solar_time=False,
    )
    c = r["chart"]
    evidence = c["yuantang_derivation"]
    HeluoYuantangDerivation.model_validate(evidence)
    assert c["yangLing"] is case["half_year"]
    assert c["xian"]["yuan"] == evidence["placement"]["selected_pos"] == case["yuan"]
    assert evidence["half_year"]["basis"] == c["yangLingBasis"] == "solstice_instant"
    assert evidence["half_year"]["birth_instant_utc"] == r["solar_term"]["anchor_utc"]
    trace = next(
        t["facts"]
        for t in r["numerology_evidence"]["rule_trace"]
        if t["rule_id"] == RULESET_ID
    )
    assert trace == evidence
    before = copy.deepcopy(c["hou"])
    evidence["half_year"]["counterfactuals"][int(case["half_year"])]["hou_lines"][0] = 9
    assert c["hou"] == before
    assert trace["half_year"]["counterfactuals"][0]["hou_lines"][0] != 9
    assert "[元堂起例与阴阳令]" in r["snapshot_text"]
