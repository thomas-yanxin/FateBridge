def test_mansion_membership_against_independent_exact_interval_search():
    boundaries = chart()["guolao"]["mansion_boundaries"]
    ordered = sorted(boundaries, key=lambda b: b["right_ascension"])
    assert len({b["star"] for b in boundaries}) == 28
    probes = [0.0, 360.0, math.nextafter(0.0, -math.inf)]
    for boundary in boundaries:
        value = boundary["right_ascension"]
        probes.extend(
            [math.nextafter(value, -math.inf), value, math.nextafter(value, math.inf)]
        )
    rng = random.Random(10123)
    probes.extend(rng.uniform(-1080, 1080) for _ in range(2000))
    for value in probes:
        exact = Fraction(value) % 360
        candidates = [b for b in ordered if Fraction(b["right_ascension"]) <= exact]
        expected = (candidates or ordered)[-1]
        actual = guolao.mansion_at(value, boundaries)
        assert actual["su28"] == expected["su28"], value
        assert 0 <= actual["degree_in_mansion"] < actual["mansion_width"]
        assert 0 <= actual["right_ascension"] < 360
    widths = [
        guolao.mansion_at(b["right_ascension"], boundaries)["mansion_width"]
        for b in boundaries
    ]
    assert sum(widths) == pytest.approx(360)
    assert max(widths) - min(widths) > 20


