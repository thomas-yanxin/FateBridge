def test_seven_physical_bodies_against_21_frozen_nasa_positions():
    fixture = json.loads((FIXTURES / "jyotish-horizons.json").read_text())
    cache = {}
    errors = []
    for reference in fixture["references"]:
        assert (
            hashlib.sha256(reference["response"]["result"].encode()).hexdigest()
            == reference["response_sha256"]
        )
        for row in reference["rows"]:
            dt = datetime.fromisoformat(row["utc"])
            if row["utc"] not in cache:
                cache[row["utc"]] = chart(
                    birth_year=dt.year,
                    birth_month=dt.month,
                    birth_day=dt.day,
                    birth_hour=dt.hour,
                    birth_minute=dt.minute,
                    birth_timezone="UTC",
                )
            body = next(
                b
                for b in cache[row["utc"]]["guolao"]["bodies"]
                if b["id"] == reference["body"]
            )
            delta = (
                body["longitude"] - row["apparent_ecliptic_longitude"] + 180
            ) % 360 - 180
            errors.append(abs(delta) * 3600)
    assert len(errors) == 21
    assert (
        max(errors) < 2.0
    )  # predeclared model-difference tolerance, not a global guarantee


def test_tt_ut1_and_proleptic_gregorian_are_explicit():
    result = chart(
        birth_year=2000,
        birth_month=2,
        birth_day=29,
        birth_hour=18,
        birth_minute=15,
        birth_timezone="UTC",
    )
    profile = result["guolao"]["profile"]
    civil = (
        2451544.5
        + (datetime(2000, 2, 29, 18, 15) - datetime(2000, 1, 1)).total_seconds() / 86400
    )
    assert (profile["julian_day_tt"] - civil) * 86400 == pytest.approx(
        64.184, abs=0.0001
    )
    assert 0.1 < (profile["julian_day_ut1"] - civil) * 86400 < 0.5
    ancient = chart(
        birth_year=1500,
        birth_month=4,
        birth_day=6,
        birth_hour=9,
        birth_minute=33,
        birth_timezone="UTC",
    )
    assert ancient["guolao"]["profile"]["calendar"] == "proleptic_gregorian"
    # Calendar date arithmetic independent of Swiss's Julian/Gregorian switch.
    historical = (
        2451544.5
        + (datetime(1500, 4, 6, 9, 33) - datetime(2000, 1, 1)).total_seconds() / 86400
    )
    assert ancient["guolao"]["profile"]["julian_day_ut1"] == pytest.approx(
        historical, abs=1e-8
    )


def test_solar_clock_cannot_change_physical_instant_or_chart():
    off = chart(birth_longitude=75.0, birth_latitude=39.0, use_true_solar_time=False)
    on = chart(birth_longitude=75.0, birth_latitude=39.0, use_true_solar_time=True)
    assert off["guolao"]["bodies"] == on["guolao"]["bodies"]
    assert off["angles"] == on["angles"]
    assert off["guolao"]["life_palace"]["clock_basis"] == "recorded_civil_clock"
    assert on["guolao"]["life_palace"]["clock_basis"] == "apparent_solar_display"
    # The ordinal birth hour may change; the physical sky must not.
    assert (
        off["guolao"]["life_palace"]["birth_hour_branch"]
        != on["guolao"]["life_palace"]["birth_hour_branch"]
    )
    assert off["person_info"]["utc_datetime"] == on["person_info"]["utc_datetime"]
    assert (
        on["guolao"]["profile"]["solar_clock_display"]
        != on["person_info"]["birth_datetime"]
    )
    assert not on["guolao"]["profile"]["solar_clock_changes_instant"]


