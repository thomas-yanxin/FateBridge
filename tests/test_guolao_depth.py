def test_shared_time_conversion_initializes_a_fresh_worker_after_catalogue_close():
    from fatebridge.core.astro.time_scales import ephemeris_time

    def in_new_worker(_):
        with runtime.preserve_ephemeris_path():
            runtime.swe.close()
        instant = datetime(2000, 2, 29, 18, 15, tzinfo=timezone.utc)
        times = ephemeris_time(instant)
        return (times.jd_tt - times.jd_utc) * 86400

    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(in_new_worker, range(4)))
    assert results == pytest.approx([64.184] * 4, abs=0.0001)
